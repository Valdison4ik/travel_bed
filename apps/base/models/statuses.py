    # до заезда (или досрочно во время проживания). В зависимости от правил тарифа и
    # сроков отмены гостю возвращается вся сумма, ее часть или удерживается штраф.
    DECLINED = 'declined', _('Отклонено')
    EXPIRED = 'expired', _('Истек срок действия')
    NO_SHOW = 'no-show', _('Незаезд')


